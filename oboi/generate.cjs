function clientQuery(page) {
  if (!page.slug) return '';
  if (page.slug === 'phone') return 'res=phone';
  if (page.slug === 'ultrawide') return 'res=ultrawide';
  if (page.slug === '4k') return 'res=3840x2160';
  if (page.slug === '1920x1080') return 'res=1920x1080';
  if (page.slug === '2560x1440') return 'res=2560x1440';
  if (page.params && page.params.q) {
    return 'q=' + encodeURIComponent(page.params.q);
  }
  return '';
}

async function generatePage(page, items, total) {
  page.total = total;
  const dir = page.slug ? path.join(OUT, page.slug) : OUT;
  fs.mkdirSync(dir, { recursive: true });
  const html = headHtml(page, items);
  const file = path.join(dir, 'index.html');
  fs.writeFileSync(file, html, 'utf8');
  console.log('  OK ' + routeFor(page.slug) + ' — ' + items.length + ' шт., всего ' + total);
}

function sitemap() {
  const urls = PAGES.map((page) => {
    const priority = page.kind === 'hub' ? '1.0' : page.kind === 'game' ? '0.7' : '0.8';
    const freq = page.kind === 'hub' ? 'daily' : 'weekly';
    return '  <url><loc>' + urlFor(page.slug) + '</loc><lastmod>' + TODAY + '</lastmod><changefreq>' + freq + '</changefreq><priority>' + priority + '</priority></url>';
  }).join('\n');
  fs.writeFileSync(
    path.join(OUT, 'sitemap.xml'),
    '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls + '\n</urlset>\n',
    'utf8'
  );
  console.log('  OK sitemap.xml — ' + PAGES.length + ' URL');
}

function injectHome(items) {
  const file = path.join(OUT, 'index.html');
  if (!fs.existsSync(file)) return;
  let html = fs.readFileSync(file, 'utf8');
  const start = '<!--OBOI:HOME:START-->';
  const end = '<!--OBOI:HOME:END-->';
  if (!html.includes(start) || !html.includes(end)) return;
  const page = PAGES[0];
  const block = '\n' + cardsHtml(items, page) + '\n';
  html = html.replace(new RegExp(start + '[\\s\\S]*?' + end), start + block + end);

  // Заполняем ItemList в JSON-LD главной реальными изображениями.
  const ldItems = items.map((item, index) => ({
    '@type': 'ListItem',
    position: index + 1,
    item: {
      '@type': 'ImageObject',
      name: page.altPrefix + ' — ' + item.res,
      contentUrl: item.full,
      thumbnailUrl: item.thumb,
      width: item.width,
      height: item.height,
      encodingFormat: item.full.endsWith('.png') ? 'image/png' : 'image/jpeg'
    }
  }));
  html = html.replace('"__OBOI_LD__"', JSON.stringify(ldItems));
  html = html.replace('"__OBOI_DATE__"', JSON.stringify(TODAY));

  fs.writeFileSync(file, html, 'utf8');
  console.log('  OK index.html — статическая выдача и ItemList обновлены');
}

function writeData(home, totals, pagesData) {
  const data = {
    generatedAt: new Date().toISOString(),
    source: 'Wallhaven',
    home,
    total: totals.home || home.length,
    presets: totals,
    pages: pagesData || {}
  };
  fs.writeFileSync(path.join(OUT, 'data.json'), JSON.stringify(data), 'utf8');
  console.log('  OK data.json — ' + home.length + ' обоев, ' + Object.keys(data.pages).length + ' подборок');
}

async function main() {
  console.log('Генерация раздела «Игровые обои»…');
  const results = [];
  const totals = {};

  for (const page of PAGES) {
    try {
      const result = await fetchWallpapers(page, 1);
      results.push({ page, result });
      totals[page.slug || 'home'] = result.total;
      await sleep(1500);
    } catch (error) {
      console.error('  FAIL ' + routeFor(page.slug) + ': ' + error.message);
      results.push({ page, result: { items: [], total: 0 } });
      totals[page.slug || 'home'] = 0;
    }
  }

  const pagesData = {};
  for (const { page, result } of results) {
    if (page.slug && result.items.length) {
      await generatePage(page, result.items, result.total);
      pagesData[page.slug] = { items: result.items, total: result.total };
    } else if (!page.slug && !result.items.length) {
      console.error('  SKIP /oboi/: нет данных для главной');
    }
  }

  const home = results.find((entry) => entry.page.slug === '') || { result: { items: [] } };
  injectHome(home.result.items);
  writeData(home.result.items, totals, pagesData);
  sitemap();
  console.log('Готово.');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});

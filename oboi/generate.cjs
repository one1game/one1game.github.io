function jsonLd(page, items) {
  const crumbs = [
    { '@type': 'ListItem', position: 1, name: 'Главная', item: ORIGIN + '/' },
    { '@type': 'ListItem', position: 2, name: 'Игровые обои', item: ORIGIN + '/oboi/' }
  ];
  if (page.slug) {
    crumbs.push({ '@type': 'ListItem', position: 3, name: page.h1.replace(/<[^>]+>/g, ''), item: urlFor(page.slug) });
  }

  const collection = {
    '@context': 'https://schema.org',
    '@type': 'CollectionPage',
    name: page.title,
    description: page.description,
    url: urlFor(page.slug),
    inLanguage: 'ru-RU',
    dateModified: TODAY,
    isPartOf: { '@type': 'WebSite', name: 'One1Game', url: ORIGIN + '/' },
    mainEntity: {
      '@type': 'ItemList',
      numberOfItems: items.length,
      itemListElement: items.map((item, index) => ({
        '@type': 'ListItem',
        position: index + 1,
        item: {
          '@type': 'ImageObject',
          name: page.altPrefix + ' — ' + item.res,
          contentUrl: item.full,
          thumbnailUrl: item.thumb,
          width: item.width,
          height: item.height,
          encodingFormat: item.full.endsWith('.png') ? 'image/png' : 'image/jpeg'
        }
      }))
    }
  };

  const faq = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: page.faq.map(([q, a]) => ({
      '@type': 'Question',
      name: q,
      acceptedAnswer: { '@type': 'Answer', text: a }
    }))
  };

  const parts = [collection, {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: crumbs
  }, faq];

  if (page.kind === 'hub') {
    parts.push({
      '@context': 'https://schema.org',
      '@type': 'WebApplication',
      name: 'Галерея игровых обоев One1Game',
      url: ORIGIN + '/oboi/',
      applicationCategory: 'MultimediaApplication',
      operatingSystem: 'Any',
      offers: { '@type': 'Offer', price: '0', priceCurrency: 'RUB' },
      description: 'Поиск и скачивание игровых обоев в 4K и Full HD с фильтрами по разрешению и устройству.'
    });
  }

  return parts.map((part) => '<script type="application/ld+json">' + JSON.stringify(part) + '</script>').join('\n');
}


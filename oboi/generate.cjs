// ── Утилиты ─────────────────────────────────────────────────

function esc(value) {
  return String(value == null ? '' : value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function routeFor(slug) {
  return slug ? '/oboi/' + slug + '/' : '/oboi/';
}

function urlFor(slug) {
  return ORIGIN + routeFor(slug);
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function paramsFor(page, pageNum) {
  const params = new URLSearchParams();
  const merged = Object.assign({}, BASE_PARAMS, page.params || {});
  // Точное разрешение важнее общего atleast: иначе API подмешивает любые
  // изображения «не меньше 1920×1080».
  if (page.params && page.params.resolutions && page.params.atleast === undefined) {
    delete merged.atleast;
  }
  // Для страниц игр важнее релевантность запросу, а для подборок —
  // популярные за всё время: так база выглядит и ощущается больше.
  if (page.kind === 'game') {
    merged.sorting = 'relevance';
    delete merged.topRange;
  } else {
    merged.sorting = 'favorites';
    delete merged.topRange;
  }
  // topRange имеет смысл только для toplist.
  if (merged.sorting !== 'toplist') delete merged.topRange;
  for (const [key, value] of Object.entries(merged)) {
    if (value != null && value !== '') params.set(key, value);
  }
  params.set('purity', '100');
  params.set('page', String(pageNum || 1));
  return params;
}

async function fetchWallpapers(page, pageNum) {
  const target = API + '?' + paramsFor(page, pageNum).toString();
  const res = await fetch(target, {
    headers: { 'User-Agent': UA, Accept: 'application/json' }
  });
  if (!res.ok) throw new Error('Wallhaven ' + res.status + ' для ' + target);
  const json = await res.json();
  return {
    items: (json.data || []).map((item) => ({
      id: item.id,
      thumb: item.thumbs && item.thumbs.large ? item.thumbs.large : item.path,
      full: item.path,
      page: item.url,
      width: item.dimension_x,
      height: item.dimension_y,
      res: item.resolution,
      source: 'Wallhaven',
      added: item.created_at
    })),
    total: json.meta ? json.meta.total : 0,
    page: json.meta ? json.meta.current_page : pageNum,
    lastPage: json.meta ? json.meta.last_page : pageNum
  };
}

function cardHtml(item, page, index) {
  const alt = page.altPrefix + ' — ' + item.res;
  const eager = (index || 0) < 4;
  return (
    '<article class="wall-card" data-id="' + esc(item.id) + '">' +
      '<a class="wall-card__media" href="' + esc(item.full) + '" target="_blank" rel="noopener" aria-label="' + esc(alt) + '">' +
        '<img src="' + esc(item.thumb) + '" alt="' + esc(alt) + '" width="' + esc(item.width) + '" height="' + esc(item.height) + '" loading="' + (eager ? 'eager' : 'lazy') + '"' + (eager ? ' fetchpriority="high"' : '') + ' decoding="async">' +
        '<span class="wall-card__res">' + esc(item.res) + '</span>' +
      '</a>' +
      '<div class="wall-card__actions">' +
        '<a class="wall-card__btn" href="' + esc(item.full) + '" target="_blank" rel="noopener" download><i class="fas fa-download" aria-hidden="true"></i><span>Скачать</span></a>' +
        '<a class="wall-card__btn" href="' + esc(item.page) + '" target="_blank" rel="noopener nofollow"><i class="fas fa-arrow-up-right-from-square" aria-hidden="true"></i><span>Источник</span></a>' +
      '</div>' +
    '</article>'
  );
}

function cardsHtml(items, page) {
  return items.map((item, index) => cardHtml(item, page, index)).join('\n');
}

function relatedHtml(page) {
  const links = page.related
    .map((slug) => {
      const target = PAGES.find((p) => p.slug === slug);
      if (!target) return '';
      return '<a href="' + routeFor(target.slug) + '">' + esc(target.h1.replace(/<[^>]+>/g, '')) + '</a>';
    })
    .filter(Boolean)
    .join('');
  return '<div class="oboi-related">' + links + '<a href="' + routeFor('') + '">Все игровые обои</a></div>';
}

function faqHtml(page) {
  return page.faq
    .map(([q, a]) => '<details><summary>' + esc(q) + '</summary><p>' + esc(a) + '</p></details>')
    .join('\n');
}

